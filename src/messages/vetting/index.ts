function rubricMessages() {
  const out = { en: {} as Record<string, string>, az: {} as Record<string, string>, ru: {} as Record<string, string> };
  for (const seed of RUBRIC_SEEDS) {
    const m = seedMessages(seed);
    Object.assign(out.en, m.en);
    Object.assign(out.az, m.az);
    Object.assign(out.ru, m.ru);
  }
  return out;
}
